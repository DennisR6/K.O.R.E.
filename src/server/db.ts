	/** Creates a consistent SQLite image for an authenticated operator backup. */
	exportSnapshot(): Uint8Array {
		// Bun's serialize() can produce an incomplete image for a live WAL-backed
		// file database. Checkpoint first, then VACUUM INTO creates a consistent
		// backup including all committed schema pages and blobs.
		this.db.run("PRAGMA wal_checkpoint(FULL)");
		const directory = mkdtempSync("/tmp/kore-backup-");
		const backupPath = `${directory}/backup.sqlite`;
		try {
			const escapedPath = backupPath.replaceAll("'", "''");
			this.db.run(`VACUUM INTO '${escapedPath}'`);
			return new Uint8Array(readFileSync(backupPath));
		} finally {
			rmSync(directory, { recursive: true, force: true });
		}
	}

	public createGame(game: StoredGame): void {
		// The immutable origin is stored independently from the mutable live
		// snapshot. Never fabricate it from `settings`: a live snapshot from a
		// later turn is not a reproducible replay origin.
		const snapshot = compress({ settings: game.settings, initialSettings: game.initialSettings, actions: game.actions ?? [], ...(game.ranked ? { ranked: game.ranked } : {}) });
		const lifecycle = game.lifecycle ?? createLifecycle("resident", game.updatedAt, game.updatedAt);
		this.db.transaction(() => {
			this.db.query(`
				INSERT INTO games (id, snapshot, current_team, turn_number, updated_at, map_id)
				VALUES (?1, ?2, ?3, ?4, ?5, ?6)
			`).run(game.id, snapshot, game.currentTeam, game.turnNumber, game.updatedAt, game.mapId ?? "unknown");
			this.writeLifecycle(game.id, lifecycle);
			const insertPlayer = this.db.query("INSERT INTO game_players (game_id, user_id, team, connected) VALUES (?1, ?2, ?3, 0)");
			game.users.forEach((user, team) => insertPlayer.run(game.id, user, team));
		})();
	}

	public saveGame(game: StoredGame): void {
		const snapshot = compress({ settings: game.settings, initialSettings: game.initialSettings, actions: game.actions ?? [], ...(game.ranked ? { ranked: game.ranked } : {}) });
		this.db.transaction(() => {
			this.db.query(`
			UPDATE games
			SET snapshot = ?2, current_team = ?3, turn_number = ?4, updated_at = ?5, map_id = ?6
			WHERE id = ?1
			`).run(game.id, snapshot, game.currentTeam, game.turnNumber, game.updatedAt, game.mapId ?? "unknown");
			if (game.lifecycle) this.writeLifecycle(game.id, game.lifecycle);
		})();
	}

	public loadGame(id: string): StoredGame | undefined {
		const row = this.db.query("SELECT id, snapshot, current_team, turn_number, updated_at, map_id FROM games WHERE id = ?1")
			.get(id) as StoredGameRow | null;
		if (!row) return undefined;
		const users = this.db.query("SELECT user_id FROM game_players WHERE game_id = ?1 ORDER BY team ASC")
			.all(id) as StoredUserRow[];
		const lifecycle = this.getLifecycle(id);
		if (!lifecycle) throw new Error(`Missing lifecycle state for game ${id}`);
		const decompressed = decompress(row.snapshot);
		return {
			id: row.id,
			settings: decompressed.settings,
			// Missing origins stay missing: legacy rows without a stored
			// initialSettings cannot fabricate one from the live snapshot.
			initialSettings: decompressed.initialSettings,
			actions: decompressed.actions,
			users: users.map(user => user.user_id),
			currentTeam: row.current_team,
			turnNumber: row.turn_number,
			updatedAt: row.updated_at,
			mapId: row.map_id,
			...(decompressed.ranked ? { ranked: decompressed.ranked } : {}),
			lifecycle,
		};
	}

