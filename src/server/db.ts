	public createReplayShare(gameId: string, replay: FrozenReplayDocument, now: number = Date.now()): StoredReplayShare {
		validateFrozenReplayDocument(replay);
		validateReplayOrigin(replay);
		const lifecycle = this.getLifecycle(gameId);
		if (lifecycle?.status !== "completed") throw new Error("Replay shares require a completed match");
		const existing = this.db.query("SELECT token, replay_json, created_at, revoked_at FROM replay_shares WHERE game_id = ?1").get(gameId) as { token: string; replay_json: string; created_at: number; revoked_at: number | null } | null;
		if (existing?.revoked_at === null) {
			try {
				const storedReplay = JSON.parse(existing.replay_json) as FrozenReplayDocument;
				validateFrozenReplayDocument(storedReplay);
				return { token: existing.token, replay: structuredClone(storedReplay), createdAt: existing.created_at, revokedAt: null };
			} catch { throw new Error("Stored replay share is invalid"); }
		}
		// `game_id` is intentionally unique. A revoked share is replaced so either
		// participant can publish a fresh token without reviving the old URL.
		if (existing) this.db.query("DELETE FROM replay_shares WHERE game_id = ?1").run(gameId);
		const token = crypto.randomUUID().replaceAll("-", "");
		this.db.query("INSERT INTO replay_shares (token, game_id, replay_json, created_at) VALUES (?1, ?2, ?3, ?4)")
			.run(token, gameId, JSON.stringify(replay), now);
		return { token, replay: structuredClone(replay), createdAt: now, revokedAt: null };
	}

	/** Public lookup intentionally omits game IDs and the frozen final snapshot. */
	public getPublicReplayShare(token: string): PublicReplayShare | undefined {
		if (!/^[a-f0-9]{32}$/.test(token)) return undefined;
		const row = this.db.query("SELECT replay_json, created_at, revoked_at FROM replay_shares WHERE token = ?1").get(token) as { replay_json: string; created_at: number; revoked_at: number | null } | null;
		if (!row || row.revoked_at !== null || row.replay_json.length > 2_000_000) return undefined;
		try {
			const replay = JSON.parse(row.replay_json) as FrozenReplayDocument;
			validateFrozenReplayDocument(replay);
			// Shares persisted before origin validation may still carry an
			// unplayable live fallback; those are treated as revoked.
			validateReplayOrigin(replay);
			const { finalSettings: _privateFinalSnapshot, ...publicReplay } = replay;
			return { token, replay: publicReplay, createdAt: row.created_at };
		} catch { return undefined; }
	}

	/** Upserts a private, operator-generated view token with the latest persisted actions. */
	public createOperatorReplayView(gameId: string, replay: ReplayDocument, now: number = Date.now()): PublicOperatorReplayView {
		validateReplayDocument(replay);
		validateReplayOrigin(replay);
		if (!this.hasGame(gameId)) {
			if (!this.hasOfflineMatch(gameId)) throw new Error("Unknown game");
			const existing = this.db.query("SELECT token FROM offline_operator_replay_views WHERE offline_match_id = ?1").get(gameId) as { token: string } | null;
			if (existing) {
				this.db.query("UPDATE offline_operator_replay_views SET replay_json = ?2, updated_at = ?3 WHERE offline_match_id = ?1").run(gameId, JSON.stringify(replay), now);
				return { token: existing.token, replay: structuredClone(replay), updatedAt: now };
			}
			const token = crypto.randomUUID().replaceAll("-", "");
			this.db.query("INSERT INTO offline_operator_replay_views (token, offline_match_id, replay_json, updated_at) VALUES (?1, ?2, ?3, ?4)").run(token, gameId, JSON.stringify(replay), now);
			return { token, replay: structuredClone(replay), updatedAt: now };
		}
		const existing = this.db.query("SELECT token FROM operator_replay_views WHERE game_id = ?1").get(gameId) as { token: string } | null;
		if (existing) {
			this.db.query("UPDATE operator_replay_views SET replay_json = ?2, updated_at = ?3 WHERE game_id = ?1").run(gameId, JSON.stringify(replay), now);
			return { token: existing.token, replay: structuredClone(replay), updatedAt: now };
		}
		const token = crypto.randomUUID().replaceAll("-", "");
		this.db.query("INSERT INTO operator_replay_views (token, game_id, replay_json, updated_at) VALUES (?1, ?2, ?3, ?4)").run(token, gameId, JSON.stringify(replay), now);
		return { token, replay: structuredClone(replay), updatedAt: now };
	}

	/** Resolves only an opaque token; game IDs and final snapshots never leave this lookup. */
	public getPublicOperatorReplayView(token: string): PublicOperatorReplayView | undefined {
		if (!/^[a-f0-9]{32}$/.test(token)) return undefined;
		const row = this.db.query("SELECT replay_json, updated_at FROM operator_replay_views WHERE token = ?1").get(token) as { replay_json: string; updated_at: number } | null;
		const offlineRow = row ?? this.db.query("SELECT replay_json, updated_at FROM offline_operator_replay_views WHERE token = ?1").get(token) as { replay_json: string; updated_at: number } | null;
		if (!offlineRow || offlineRow.replay_json.length > 2_000_000) return undefined;
		try {
			const replay = JSON.parse(offlineRow.replay_json) as ReplayDocument;
			validateReplayDocument(replay);
			// The operator may have snapshotted a legacy live fallback before
			// origin validation existed; such views are unplayable and are no
			// longer served instead of failing inside the viewer.
			validateReplayOrigin(replay);
			return { token, replay: structuredClone(replay), updatedAt: offlineRow.updated_at };
		} catch { return undefined; }
	}

	public revokeReplayShare(token: string, now: number = Date.now()): boolean {
		if (!/^[a-f0-9]{32}$/.test(token)) return false;
		return this.db.query("UPDATE replay_shares SET revoked_at = ?2 WHERE token = ?1 AND revoked_at IS NULL").run(token, now).changes > 0;
	}

	public getCompressedSnapshotSize(id: string): number | undefined {
		const row = this.db.query("SELECT length(snapshot) AS size FROM games WHERE id = ?1").get(id) as { size: number } | null;
		return row?.size;
	}

