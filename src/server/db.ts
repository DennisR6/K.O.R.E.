	public getMetricCounts(): { allTime: number; offlineMatches: number; playtestMatches: number; offlineModes: OfflineModeMetric[]; playersAllTime: number; playersOnline: number; paused: number; sleeping: number } {
		const allTime = this.db.query("SELECT count(*) AS count FROM games").get() as { count: number };
		const offlineMatches = this.db.query("SELECT count(*) AS count FROM offline_matches").get() as { count: number };
		const playtestMatches = this.db.query("SELECT count(*) AS count FROM offline_matches WHERE playtest = 1").get() as { count: number };
		const playerIds = new Set((this.db.query("SELECT user_id FROM game_players").all() as Array<{ user_id: string }>).map(row => row.user_id));
		const offlinePlayers = this.db.query("SELECT players_json FROM offline_matches").all() as Array<{ players_json: string }>;
		for (const row of offlinePlayers) for (const player of JSON.parse(row.players_json) as string[]) playerIds.add(player);
		const playersAllTime = { count: playerIds.size };
		const playersOnline = this.db.query("SELECT count(DISTINCT game_players.user_id) AS count FROM game_players WHERE game_players.connected = 1").get() as { count: number };
		const statuses = this.db.query(`
			SELECT status, count(*) AS count FROM game_lifecycle
			WHERE status IN ('paused', 'sleeping') GROUP BY status
		`).all() as Array<{ status: AuthoritativeMatchStatus; count: number }>;
		const counts = new Map(statuses.map(row => [row.status, row.count]));
		const offlineModes = this.db.query("SELECT mode, count(*) AS games FROM offline_matches GROUP BY mode ORDER BY games DESC, mode ASC").all() as OfflineModeMetric[];
		return { allTime: allTime.count + offlineMatches.count, offlineMatches: offlineMatches.count, playtestMatches: playtestMatches.count, offlineModes, playersAllTime: playersAllTime.count, playersOnline: playersOnline.count, paused: counts.get("paused") ?? 0, sleeping: counts.get("sleeping") ?? 0 };
	}

	/** Lists every persisted action log for authenticated operator replay lookup. */
	public listOperatorReplays(gameId?: string): OperatorReplaySummary[] {
		const rows = (gameId === undefined
			? this.db.query("SELECT games.id, games.snapshot, games.updated_at, game_lifecycle.status, replay_shares.token FROM games JOIN game_lifecycle ON game_lifecycle.game_id = games.id LEFT JOIN replay_shares ON replay_shares.game_id = games.id AND replay_shares.revoked_at IS NULL ORDER BY games.updated_at DESC, games.id ASC").all()
			: this.db.query("SELECT games.id, games.snapshot, games.updated_at, game_lifecycle.status, replay_shares.token FROM games JOIN game_lifecycle ON game_lifecycle.game_id = games.id LEFT JOIN replay_shares ON replay_shares.game_id = games.id AND replay_shares.revoked_at IS NULL WHERE games.id = ?1 ORDER BY games.updated_at DESC, games.id ASC").all(gameId)) as OperatorReplayRow[];
		const online = rows.map(row => ({ gameId: row.id, gameType: "player" as const, status: row.status, updatedAt: row.updated_at, actionCount: decompress(row.snapshot).actions.length, ...(row.token ? { replayToken: row.token } : {}) }));
		const offlineRows = (gameId === undefined
			? this.db.query("SELECT id, mode, replay_json, created_at FROM offline_matches ORDER BY created_at DESC, id ASC").all()
			: this.db.query("SELECT id, mode, replay_json, created_at FROM offline_matches WHERE id = ?1").all(gameId)) as Array<{ id: string; mode: string; replay_json: string; created_at: number }>;
		const offline = offlineRows.flatMap(row => {
			try {
				const replay = JSON.parse(row.replay_json) as ReplayDocument;
				validateReplayDocument(replay);
				return [{ gameId: row.id, gameType: row.mode === "hotseat" ? "player" as const : "ai" as const, status: "completed" as AuthoritativeMatchStatus, updatedAt: row.created_at, actionCount: replay.actions.length }];
			} catch { return []; }
		});
		return [...online, ...offline].sort((left, right) => right.updatedAt - left.updatedAt || left.gameId.localeCompare(right.gameId));
	}

	/** Returns the deterministic replay document for any persisted match. */
	public getOperatorReplay(gameId: string): ReplayDocument | undefined {
		const game = this.loadGame(gameId);
		if (!game?.initialSettings) {
			const row = this.db.query("SELECT replay_json FROM offline_matches WHERE id = ?1").get(gameId) as { replay_json: string } | null;
			if (!row) return undefined;
			try {
				const replay = JSON.parse(row.replay_json) as ReplayDocument;
				validateReplayDocument(replay);
				validateReplayOrigin(replay);
				return structuredClone(replay);
			} catch { return undefined; }
		}
		const replay: ReplayDocument = { schemaVersion: 1, initialSettings: game.initialSettings, seed: 12345, actions: game.actions ?? [] };
		validateReplayDocument(replay);
		try {
			validateReplayOrigin(replay);
		} catch {
			// A legacy row whose origin is unknown cannot be replayed; an
			// unplayable document must never be offered to the operator.
			return undefined;
		}
		return structuredClone(replay);
	}

